/**
 * The field catalogue (bundle 02-data-model, "Full field inventory"): every
 * column of the source master sheet, and where it now lives in Neuvto.
 *
 * Criterion 8 says every source column has a home in the UI and that this
 * catalogue is the checklist. So `home` is not a comment: fieldCatalogue.test.tsx
 * renders a real card and fails if any home names a tab or panel that is not
 * there.
 *
 * `visibleTo` here is descriptive. Who sees what is enforced by
 * employee_card() (§5 of NEUVTO_EMPLOYEE_MASTER) and cannot be loosened from a
 * settings screen; a setting that could would be the leak.
 *
 * `required` and `employeeCanEdit` are Neuvto's answers, as words. Since D107
 * a company's Super Admin sets both, per field, and Fields and visibility
 * shows the company's answers from employee_field_settings(); `key` is the
 * field's name there. The words stay for what a Yes or No cannot say: Derived,
 * Auto.
 */

export type CardTab =
  | "Overview"
  | "Personal"
  | "Family"
  | "Employment"
  | "Statutory and bank"
  | "History";

export interface CatalogueField {
  /** The field in employee_field_settings() (D107). */
  key: string;
  group: string;
  field: string;
  /** The master sheet's own column names, or `new` for fields the sheet lacked. */
  sheet: readonly string[] | "new";
  required: string;
  employeeCanEdit: string;
  visibleTo: string;
  inExports: string;
  /** Where it lives: the card header, or a sub-tab and the panel on it. */
  home: "Card header" | { tab: CardTab; panel: string };
}

